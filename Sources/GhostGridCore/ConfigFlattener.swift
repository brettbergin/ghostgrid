import Foundation

/// Turns a Ghostty config that uses `config-file` includes into one file.
///
/// libghostty-spm loads a config with `ghostty_config_load_file` only and
/// never calls `ghostty_config_load_recursive_files`, so includes are
/// silently dropped. This reproduces Ghostty's include semantics instead:
/// a file's own settings first, then each include in the order listed
/// (recursively), so later values win the same way. Includes are resolved
/// relative to the file that names them; a leading `?` makes one optional.
///
/// The output is written somewhere else, so relative file paths in it are
/// made absolute against the file they came from.
public enum ConfigFlattener {
    public enum Error: Swift.Error, CustomStringConvertible {
        case unreadable(path: String, underlying: any Swift.Error)

        public var description: String {
            switch self {
            case let .unreadable(path, underlying):
                "cannot read Ghostty config \(path): \(underlying.localizedDescription)"
            }
        }
    }

    /// Keys whose value is a file path relative to the config file.
    static let pathKeys: Set<String> = ["custom-shader", "background-image"]

    public static func flatten(_ entry: URL) throws -> String {
        var visited: Set<String> = []
        var output = "# Generated by ghostgrid from \(entry.path); edit that file instead.\n"
        try append(entry.standardizedFileURL, optional: false, to: &output, visited: &visited)
        return output
    }

    private static func append(
        _ file: URL,
        optional: Bool,
        to output: inout String,
        visited: inout Set<String>,
    ) throws {
        let path = file.resolvingSymlinksInPath().path
        guard visited.insert(path).inserted else { return }

        let text: String
        do {
            text = try String(contentsOf: file, encoding: .utf8)
        } catch {
            if optional { return }
            throw Error.unreadable(path: file.path, underlying: error)
        }

        let base = file.deletingLastPathComponent()
        var includes: [(url: URL, optional: Bool)] = []
        output += "\n# --- \(file.path)\n"

        for rawLine in text.split(separator: "\n", omittingEmptySubsequences: false) {
            let line = String(rawLine)
            guard let (key, value) = setting(line) else {
                output += line + "\n"
                continue
            }
            if key == "config-file" {
                var target = unquote(value)
                let isOptional = target.hasPrefix("?")
                if isOptional { target.removeFirst() }
                guard !target.isEmpty else { continue }
                includes.append((resolve(target, against: base), isOptional))
            } else if pathKeys.contains(key), isRelativePath(unquote(value)) {
                output += "\(key) = \(resolve(unquote(value), against: base).path)\n"
            } else {
                output += line + "\n"
            }
        }

        for include in includes {
            try append(include.url, optional: include.optional, to: &output, visited: &visited)
        }
    }

    /// `key = value` for a setting line, nil for comments and blanks.
    private static func setting(_ line: String) -> (String, String)? {
        let trimmed = line.trimmingCharacters(in: .whitespaces)
        guard !trimmed.isEmpty, !trimmed.hasPrefix("#"),
              let equals = trimmed.firstIndex(of: "=")
        else { return nil }
        let key = trimmed[..<equals].trimmingCharacters(in: .whitespaces)
        let value = trimmed[trimmed.index(after: equals)...].trimmingCharacters(in: .whitespaces)
        return (key, value)
    }

    private static func unquote(_ value: String) -> String {
        guard value.count >= 2, value.hasPrefix("\""), value.hasSuffix("\"") else { return value }
        return String(value.dropFirst().dropLast())
    }

    private static func isRelativePath(_ value: String) -> Bool {
        !value.isEmpty && !value.hasPrefix("/") && !value.hasPrefix("~")
    }

    private static func resolve(_ path: String, against base: URL) -> URL {
        if path.hasPrefix("~") {
            return URL(fileURLWithPath: (path as NSString).expandingTildeInPath)
        }
        if path.hasPrefix("/") { return URL(fileURLWithPath: path) }
        return base.appendingPathComponent(path).standardizedFileURL
    }
}
