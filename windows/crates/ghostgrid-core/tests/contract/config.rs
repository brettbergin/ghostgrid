//! Contract for reading the Ghostty config (ConfigFlattenerTests,
//! GhosttyConfigValuesTests), with Windows paths and line endings, and for
//! finding the config on Windows.

use crate::support::directory;
use ghostgrid_core::config::{find_config, flatten, flatten_with_home, ConfigError, ConfigValues};
use std::collections::{HashMap, HashSet};
use std::path::{Path, PathBuf};

/// Non-comment, non-blank lines of the flattened output.
fn settings(text: &str) -> Vec<String> {
    text.split('\n')
        .filter(|line| !line.starts_with('#') && !line.trim().is_empty())
        .map(String::from)
        .collect()
}

#[test]
fn includes_load_after_the_including_file_in_order() {
    // Ghostty loads config-file includes after the whole including file,
    // in the order listed, so a later include wins over the main file.
    let dir = directory(&[
        ("config.ghostty", "font-size = 12\nconfig-file = a.ghostty\nconfig-file = b.ghostty\ncursor-style = block\n"),
        ("a.ghostty", "font-size = 13\n"),
        ("b.ghostty", "font-size = 14\n"),
    ]);
    let out = flatten(&dir.join("config.ghostty")).unwrap();
    assert_eq!(
        settings(&out),
        [
            "font-size = 12",
            "cursor-style = block",
            "font-size = 13",
            "font-size = 14"
        ]
    );
    assert!(out.starts_with("# Generated by ghostgrid from "));
}

#[test]
fn nested_includes_resolve_relative_to_their_own_file() {
    let dir = directory(&[
        ("config", "config-file = sub/one.ghostty\n"),
        (
            "sub/one.ghostty",
            "config-file = two.ghostty\nfont-size = 1\n",
        ),
        ("sub/two.ghostty", "font-size = 2\n"),
    ]);
    assert_eq!(
        settings(&flatten(&dir.join("config")).unwrap()),
        ["font-size = 1", "font-size = 2"]
    );
}

#[test]
fn optional_missing_include_is_skipped_but_required_one_fails() {
    let dir = directory(&[
        ("ok", "config-file = ?missing.ghostty\nfont-size = 1\n"),
        ("bad", "config-file = missing.ghostty\n"),
    ]);
    assert_eq!(
        settings(&flatten(&dir.join("ok")).unwrap()),
        ["font-size = 1"]
    );
    let error = flatten(&dir.join("bad")).unwrap_err();
    assert!(matches!(error, ConfigError::Unreadable { .. }));
    assert!(
        error.to_string().starts_with("cannot read Ghostty config "),
        "{error}"
    );
}

#[test]
fn quoted_include_paths_work() {
    let dir = directory(&[
        ("config", "config-file = \"my file.ghostty\"\n"),
        ("my file.ghostty", "font-size = 9\n"),
    ]);
    assert_eq!(
        settings(&flatten(&dir.join("config")).unwrap()),
        ["font-size = 9"]
    );
}

#[test]
fn include_cycles_are_broken() {
    let dir = directory(&[
        ("a", "config-file = b\nfont-size = 1\n"),
        ("b", "config-file = a\nfont-size = 2\n"),
    ]);
    assert_eq!(
        settings(&flatten(&dir.join("a")).unwrap()),
        ["font-size = 1", "font-size = 2"]
    );
}

#[test]
fn relative_file_paths_become_absolute() {
    let dir = directory(&[
        ("config", "config-file = fx/effects.ghostty\ncustom-shader = top.glsl\nbackground-image = \"my image.png\"\n"),
        (
            "fx/effects.ghostty",
            "custom-shader = shaders/trail.glsl\ncustom-shader = /abs/x.glsl\ncustom-shader = ~/home.glsl\n\
             custom-shader = C:\\abs\\y.glsl\ncustom-shader = D:/abs/z.glsl\ncustom-shader = \\\\server\\share\\w.glsl\n",
        ),
    ]);
    let out = settings(&flatten(&dir.join("config")).unwrap());
    assert_eq!(
        out,
        [
            format!("custom-shader = {}", dir.join("top.glsl").display()),
            format!("background-image = {}", dir.join("my image.png").display()),
            format!(
                "custom-shader = {}",
                dir.join("fx").join("shaders").join("trail.glsl").display()
            ),
            "custom-shader = /abs/x.glsl".into(),
            "custom-shader = ~/home.glsl".into(),
            "custom-shader = C:\\abs\\y.glsl".into(),
            "custom-shader = D:/abs/z.glsl".into(),
            "custom-shader = \\\\server\\share\\w.glsl".into(),
        ]
    );
}

#[test]
fn other_lines_pass_through_unchanged() {
    let dir = directory(&[(
        "config",
        "theme = light:Catppuccin Latte,dark:Catppuccin Mocha Black\nkeybind = global:ctrl+grave_accent=toggle_quick_terminal\n",
    )]);
    assert_eq!(
        settings(&flatten(&dir.join("config")).unwrap()),
        [
            "theme = light:Catppuccin Latte,dark:Catppuccin Mocha Black",
            "keybind = global:ctrl+grave_accent=toggle_quick_terminal",
        ]
    );
}

#[test]
fn crlf_files_and_a_byte_order_mark_read_like_unix_ones() {
    let dir = directory(&[
        (
            "config",
            "\u{feff}font-size = 12\r\nconfig-file = a\r\n# note\r\n",
        ),
        ("a", "font-size = 13\r\ncustom-shader = s.glsl\r\n"),
    ]);
    let out = flatten(&dir.join("config")).unwrap();
    assert!(!out.contains('\r'));
    assert!(!out.contains('\u{feff}'));
    assert_eq!(
        settings(&out),
        [
            "font-size = 12".to_string(),
            "font-size = 13".into(),
            format!("custom-shader = {}", dir.join("s.glsl").display())
        ]
    );
}

#[test]
fn a_home_include_expands_to_the_home_folder() {
    let home = directory(&[(".config/extra.ghostty", "font-size = 21\n")]);
    let dir = directory(&[(
        "config",
        "config-file = ~/.config/extra.ghostty\nconfig-file = ?~\\nope\n",
    )]);
    let out = flatten_with_home(&dir.join("config"), Some(&home)).unwrap();
    assert_eq!(settings(&out), ["font-size = 21"]);
}

#[test]
fn an_absolute_windows_include_is_read_as_is() {
    let other = directory(&[("theme.ghostty", "font-size = 5\n")]);
    let target = other.join("theme.ghostty");
    let forward = target.display().to_string().replace('\\', "/");
    let dir = directory(&[(
        "config",
        &format!(
            "config-file = {}\nconfig-file = {forward}\n",
            target.display()
        ),
    )]);
    assert_eq!(
        settings(&flatten(&dir.join("config")).unwrap()),
        ["font-size = 5"],
        "the same file twice is a cycle"
    );
}

// ConfigValues

fn values() -> ConfigValues {
    ConfigValues::new(
        "# comment = ignored\nmouse-hide-while-typing = true\nunfocused-split-opacity = 0.85\n\
         unfocused-split-opacity = 0.7\nfont-family = \"JetBrainsMono NF\"\n",
    )
}

#[test]
fn last_value_wins_and_types_parse() {
    let config = values();
    assert!(config.bool("mouse-hide-while-typing", false));
    assert_eq!(config.double("unfocused-split-opacity", 1.0), 0.7);
    assert_eq!(config.string("font-family"), Some("JetBrainsMono NF"));
}

#[test]
fn missing_or_invalid_falls_back() {
    let config = values();
    assert!(!config.bool("copy-on-select", false));
    assert_eq!(config.double("nope", 0.5), 0.5);
    assert_eq!(config.string("# comment"), None);
    assert_eq!(ConfigValues::new("x = wide").double("x", 2.0), 2.0);
}

#[test]
fn repeatable_keys_keep_every_value_and_an_empty_one_resets_them() {
    let config = ConfigValues::new(
        "palette = 0=#111111\nfont-family = A\nfont-family = \"B C\"\npalette = 1=#222222\n",
    );
    assert_eq!(config.all("palette"), ["0=#111111", "1=#222222"]);
    assert_eq!(config.all("font-family"), ["A", "B C"]);
    assert!(config.all("nope").is_empty());
    let reset = ConfigValues::new("font-family = A\nfont-family = \"\"\nfont-family = Z\n");
    assert_eq!(reset.all("font-family"), ["Z"]);
}

#[test]
fn crlf_text_reads_like_unix_text() {
    let config = ConfigValues::new("a = 1\r\nb = \"two\"\r\n");
    assert_eq!(config.string("a"), Some("1"));
    assert_eq!(config.string("b"), Some("two"));
}

#[test]
fn keys_are_listed_in_first_seen_order() {
    let config = ConfigValues::new("b = 1\na = 2\nb = 3\n");
    assert_eq!(config.keys().collect::<Vec<_>>(), ["b", "a", "b"]);
}

// find_config

fn find(env: &[(&str, &str)], existing: &[PathBuf]) -> Option<PathBuf> {
    let env: HashMap<String, String> = env
        .iter()
        .map(|(k, v)| (k.to_string(), v.to_string()))
        .collect();
    let existing: HashSet<PathBuf> = existing.iter().cloned().collect();
    find_config(&|key| env.get(key).cloned(), &|path: &Path| {
        existing.contains(path)
    })
}

fn candidate(base: &str, name: &str) -> PathBuf {
    PathBuf::from(base).join("ghostty").join(name)
}

const ENV: [(&str, &str); 4] = [
    ("XDG_CONFIG_HOME", "D:\\xdg"),
    ("USERPROFILE", "C:\\Users\\me"),
    ("LOCALAPPDATA", "C:\\Users\\me\\AppData\\Local"),
    ("APPDATA", "C:\\Users\\me\\AppData\\Roaming"),
];

#[test]
fn ghostgrid_config_wins() {
    let mut env = ENV.to_vec();
    env.push(("GHOSTGRID_CONFIG", "E:\\mine.ghostty"));
    assert_eq!(
        find(&env, &[candidate("D:\\xdg", "config")]),
        Some(PathBuf::from("E:\\mine.ghostty"))
    );
}

#[test]
fn the_config_is_looked_for_in_each_base_in_order() {
    let profile = PathBuf::from("C:\\Users\\me\\.config");
    let profile = profile.to_str().unwrap();
    assert_eq!(find(&ENV, &[]), None);
    assert_eq!(
        find(
            &ENV,
            &[
                candidate("C:\\Users\\me\\AppData\\Roaming", "config"),
                candidate(profile, "config")
            ]
        ),
        Some(candidate(profile, "config"))
    );
    assert_eq!(
        find(
            &ENV,
            &[
                candidate("D:\\xdg", "config"),
                candidate("D:\\xdg", "config.ghostty")
            ]
        ),
        Some(candidate("D:\\xdg", "config.ghostty")),
        "config.ghostty before config"
    );
    assert_eq!(
        find(
            &ENV,
            &[candidate("C:\\Users\\me\\AppData\\Local", "config")]
        ),
        Some(candidate("C:\\Users\\me\\AppData\\Local", "config"))
    );
    assert_eq!(
        find(
            &ENV[1..],
            &[candidate(
                "C:\\Users\\me\\AppData\\Roaming",
                "config.ghostty"
            )]
        ),
        Some(candidate(
            "C:\\Users\\me\\AppData\\Roaming",
            "config.ghostty"
        )),
        "XDG_CONFIG_HOME is optional"
    );
}
