//! Reading the user's Ghostty config on Windows: finding it, inlining its
//! `config-file` includes the way Ghostty does, and reading option values
//! for the options ghostgrid implements itself ([`terminal`] maps them to
//! what xterm.js needs).

use crate::paths;
use std::collections::HashSet;
use std::fmt;
use std::path::{Path, PathBuf};

pub mod terminal;

/// Why the config could not be flattened.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum ConfigError {
    /// A required file (the entry, or an include without `?`) could not be
    /// read.
    Unreadable { path: String, message: String },
}

impl fmt::Display for ConfigError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            ConfigError::Unreadable { path, message } => {
                write!(f, "cannot read Ghostty config {path}: {message}")
            }
        }
    }
}

impl std::error::Error for ConfigError {}

/// Keys whose value is a file path relative to the config file.
const PATH_KEYS: [&str; 2] = ["custom-shader", "background-image"];

/// Turns a Ghostty config that uses `config-file` includes into one text.
///
/// This reproduces Ghostty's include semantics: a file's own settings
/// first, then each include in the order listed (recursively), so later
/// values win the same way. Includes are resolved relative to the file
/// that names them; a leading `?` makes one optional; a file already read
/// is skipped (cycles). Relative file paths in the output are made
/// absolute against the file they came from, since the text is used
/// somewhere else. `~` is the home folder (USERPROFILE, then HOME).
pub fn flatten(entry: &Path) -> Result<String, ConfigError> {
    let home = paths::home_from_env(&|key| std::env::var(key).ok()).map(PathBuf::from);
    flatten_with_home(entry, home.as_deref())
}

/// [`flatten`] with the home folder given (tests, or a caller that
/// already knows it).
pub fn flatten_with_home(entry: &Path, home: Option<&Path>) -> Result<String, ConfigError> {
    let mut visited = HashSet::new();
    let mut output = format!(
        "# Generated by ghostgrid from {}; edit that file instead.\n",
        entry.display()
    );
    let entry = PathBuf::from(paths::normalize(&entry.display().to_string()));
    let home = home.map(|h| h.display().to_string());
    append(&entry, false, &mut output, &mut visited, home.as_deref())?;
    Ok(output)
}

/// The identity of a file for cycle detection: its real path when it
/// exists, else its text without case (Windows paths ignore case).
fn identity(file: &Path) -> String {
    std::fs::canonicalize(file)
        .map(|p| p.display().to_string())
        .unwrap_or_else(|_| file.display().to_string())
        .to_lowercase()
}

fn append(
    file: &Path,
    optional: bool,
    output: &mut String,
    visited: &mut HashSet<String>,
    home: Option<&str>,
) -> Result<(), ConfigError> {
    if !visited.insert(identity(file)) {
        return Ok(());
    }
    let text = match std::fs::read_to_string(file) {
        Ok(text) => text,
        Err(_) if optional => return Ok(()),
        Err(error) => {
            return Err(ConfigError::Unreadable {
                path: file.display().to_string(),
                message: error.to_string(),
            })
        }
    };
    let text = text.strip_prefix('\u{feff}').unwrap_or(&text);
    let base = file
        .parent()
        .map(|p| p.display().to_string())
        .unwrap_or_default();
    let mut includes: Vec<(PathBuf, bool)> = Vec::new();
    output.push_str(&format!("\n# --- {}\n", file.display()));

    for raw in text.split('\n') {
        let line = raw.strip_suffix('\r').unwrap_or(raw);
        let Some((key, value)) = setting(line) else {
            output.push_str(line);
            output.push('\n');
            continue;
        };
        if key == "config-file" {
            let target = unquote(value);
            let (target, is_optional) = match target.strip_prefix('?') {
                Some(rest) => (rest, true),
                None => (target, false),
            };
            if target.is_empty() {
                continue;
            }
            includes.push((PathBuf::from(resolve(target, &base, home)), is_optional));
        } else if PATH_KEYS.contains(&key) && is_relative_path(unquote(value)) {
            output.push_str(&format!(
                "{key} = {}\n",
                resolve(unquote(value), &base, home)
            ));
        } else {
            output.push_str(line);
            output.push('\n');
        }
    }

    for (include, optional) in includes {
        append(&include, optional, output, visited, home)?;
    }
    Ok(())
}

/// `key = value` for a setting line, nil for comments and blanks.
fn setting(line: &str) -> Option<(&str, &str)> {
    let trimmed = line.trim();
    if trimmed.is_empty() || trimmed.starts_with('#') {
        return None;
    }
    let (key, value) = trimmed.split_once('=')?;
    Some((key.trim(), value.trim()))
}

fn unquote(value: &str) -> &str {
    if value.len() >= 2 && value.starts_with('"') && value.ends_with('"') {
        &value[1..value.len() - 1]
    } else {
        value
    }
}

fn is_relative_path(value: &str) -> bool {
    !value.is_empty() && !paths::is_absolute(value) && !value.starts_with('~')
}

fn resolve(path: &str, base: &str, home: Option<&str>) -> String {
    if path.starts_with('~') {
        if let Some(expanded) = home.and_then(|home| paths::expand_home(path, home)) {
            return expanded;
        }
        return path.to_string();
    }
    if paths::is_absolute(path) {
        return path.to_string();
    }
    paths::join(base, path)
}

/// Reads option values from a Ghostty config (the flattened text), for the
/// options ghostgrid implements itself.
#[derive(Debug, Clone, Default, PartialEq)]
pub struct ConfigValues {
    /// Every setting in order: repeatable keys need them all.
    entries: Vec<(String, String)>,
}

impl ConfigValues {
    pub fn new(text: &str) -> Self {
        let text = text.strip_prefix('\u{feff}').unwrap_or(text);
        let entries = text
            .split('\n')
            .filter_map(|line| setting(line.strip_suffix('\r').unwrap_or(line)))
            .map(|(key, value)| (key.to_string(), unquote(value).to_string()))
            .collect();
        ConfigValues { entries }
    }

    /// The value of `key`: the last occurrence wins, as in Ghostty; quotes
    /// are stripped.
    pub fn string(&self, key: &str) -> Option<&str> {
        self.entries
            .iter()
            .rev()
            .find(|(k, _)| k == key)
            .map(|(_, v)| v.as_str())
    }

    /// Every value of a repeatable key (palette, font-family), in order.
    /// An empty value resets the list, as Ghostty does.
    pub fn all(&self, key: &str) -> Vec<String> {
        let mut values = Vec::new();
        for (k, v) in &self.entries {
            if k == key {
                if v.is_empty() {
                    values.clear();
                } else {
                    values.push(v.clone());
                }
            }
        }
        values
    }

    /// "true" or "false" (any case); anything else is `fallback`.
    pub fn bool(&self, key: &str, fallback: bool) -> bool {
        match self.string(key).map(str::to_ascii_lowercase).as_deref() {
            Some("true") => true,
            Some("false") => false,
            _ => fallback,
        }
    }

    pub fn double(&self, key: &str, fallback: f64) -> f64 {
        self.string(key)
            .and_then(|v| v.parse::<f64>().ok())
            .unwrap_or(fallback)
    }

    /// Every key, in the order it appears (repeats included).
    pub fn keys(&self) -> impl Iterator<Item = &str> {
        self.entries.iter().map(|(k, _)| k.as_str())
    }
}

/// Where the Ghostty config is on Windows. GHOSTGRID_CONFIG wins (as is,
/// so a wrong path shows up as an error); otherwise, for each base folder
/// in [$XDG_CONFIG_HOME, %USERPROFILE%\.config, %LOCALAPPDATA%,
/// %APPDATA%], `ghostty\config.ghostty` then `ghostty\config`.
pub fn find_config(
    env: &dyn Fn(&str) -> Option<String>,
    exists: &dyn Fn(&Path) -> bool,
) -> Option<PathBuf> {
    if let Some(path) = env("GHOSTGRID_CONFIG").filter(|p| !p.is_empty()) {
        return Some(PathBuf::from(path));
    }
    let set = |key: &str| env(key).filter(|v| !v.is_empty());
    let bases = [
        set("XDG_CONFIG_HOME").map(PathBuf::from),
        set("USERPROFILE").map(|p| PathBuf::from(p).join(".config")),
        set("LOCALAPPDATA").map(PathBuf::from),
        set("APPDATA").map(PathBuf::from),
    ];
    bases.into_iter().flatten().find_map(|base| {
        ["config.ghostty", "config"]
            .iter()
            .map(|name| base.join("ghostty").join(name))
            .find(|path| exists(path))
    })
}

/// The text of Ghostty theme `name`: an absolute path is read directly;
/// otherwise each of `dirs` (user themes first, then bundled ones) is
/// tried in order.
pub fn theme_lookup(
    name: &str,
    dirs: &[PathBuf],
    read: &dyn Fn(&Path) -> Option<String>,
) -> Option<String> {
    let name = name.trim();
    if name.is_empty() {
        return None;
    }
    if paths::is_absolute(name) {
        return read(Path::new(name));
    }
    dirs.iter().find_map(|dir| read(&dir.join(name)))
}
