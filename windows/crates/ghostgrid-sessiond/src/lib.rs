//! What ghostgrid and ghostgrid-sessiond share beyond the wire format (which
//! lives in ghostgrid-core): where the helper listens, who may connect, and
//! a client for one pane's connection.
//!
//! The helper listens on a named pipe whose name carries the protocol
//! version, the user's SID and the logon session, so an update never talks
//! to an older helper with a different protocol, and two users (or two
//! logons) never share one. The pipe's DACL admits only the user and
//! SYSTEM; remote clients are refused.

#[cfg(windows)]
pub mod pipe;

/// Frames from a byte stream, as messages.
pub use ghostgrid_core::protocol::{FrameDecoder, SessionMessage, PROTOCOL_VERSION};

/// A timestamp for log lines: "2026-11-27 19:23:05Z" (UTC, no time zone
/// database needed).
pub fn timestamp() -> String {
    let secs = std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map(|d| d.as_secs() as i64)
        .unwrap_or(0);
    let (days, rem) = (secs.div_euclid(86_400), secs.rem_euclid(86_400));
    let (y, m, d) = civil_from_days(days);
    format!("{y:04}-{m:02}-{d:02} {:02}:{:02}:{:02}Z", rem / 3600, rem % 3600 / 60, rem % 60)
}

/// Howard Hinnant's days-to-civil conversion.
fn civil_from_days(z: i64) -> (i64, u32, u32) {
    let z = z + 719_468;
    let era = z.div_euclid(146_097);
    let doe = z.rem_euclid(146_097);
    let yoe = (doe - doe / 1460 + doe / 36_524 - doe / 146_096) / 365;
    let doy = doe - (365 * yoe + yoe / 4 - yoe / 100);
    let mp = (5 * doy + 2) / 153;
    let d = (doy - (153 * mp + 2) / 5 + 1) as u32;
    let m = if mp < 10 { mp + 3 } else { mp - 9 } as u32;
    let y = yoe + era * 400 + i64::from(m <= 2);
    (y, m, d)
}

#[cfg(test)]
mod tests {
    use super::civil_from_days;

    #[test]
    fn converts_days_to_dates() {
        assert_eq!(civil_from_days(0), (1970, 1, 1));
        assert_eq!(civil_from_days(20_419), (2025, 11, 27));
        assert_eq!(civil_from_days(-1), (1969, 12, 31));
        assert_eq!(civil_from_days(11_016), (2000, 2, 29));
        assert_eq!(civil_from_days(11_017), (2000, 3, 1));
    }
}
